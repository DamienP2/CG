// Plain C ABI over the Blackmagic DeckLink SDK (COM), for the Rust side
// (crates/cg-output/src/decklink.rs). Built by build.rs with the `decklink`
// feature against the headers in ../decklink-sdk/<platform>/.
//
// The DeckLink runtime (Blackmagic Desktop Video) is loaded at run time:
// on machines without it every entry point fails gracefully (the device
// iterator cannot be created) instead of the server failing to start.
//
// Threading: every handle may be used from several threads at once (the
// output is pushed to from a sender thread while the channel clock waits on
// it); state shared with the driver callbacks is guarded by a mutex.

