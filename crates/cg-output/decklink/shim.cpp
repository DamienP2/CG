typedef BSTR dl_string;
#elif defined(__APPLE__)
#include "DeckLinkAPI.h"
typedef bool dl_bool;
typedef CFStringRef dl_string;
#else
#include "DeckLinkAPI.h"
typedef bool dl_bool;
typedef const char *dl_string;
#endif

